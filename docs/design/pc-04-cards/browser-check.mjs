import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base = process.env.CARD_STUDY_URL || 'http://127.0.0.1:4318';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
await mkdir(new URL('./verification/', import.meta.url), { recursive: true });
try {
  await page.goto(`${base}/play.html`, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Dismiss introduction', exact: true }).click();
  const hand = page.locator('#hand');
  await hand.locator('forge-card').first().waitFor();
  assert.equal(await hand.locator('forge-card').count(), 7);
  assert.equal(await page.locator('#preview').isDisabled(), true);
  const blank = hand.locator('[data-card-id="your-own-idea"]');
  assert.equal(await blank.locator('button').count(), 0);
  assert.match(await blank.innerText(), /unavailable in demo/);
  const blankBackground = await blank.evaluate((el) => getComputedStyle(el).backgroundColor);
  await page.getByRole('button', { name: 'Details for Knockback', exact: true }).click();
  assert.equal(await page.locator('#inspect-dialog').isVisible(), true);
  assert.equal(await hand.locator('[selected]').count(), 0, 'Inspection must not select');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Details for Knockback', exact: true }).evaluate((el) => el === document.activeElement), true);
  const select = page.getByRole('button', { name: 'Select Knockback', exact: true });
  await select.focus(); await page.keyboard.press('Enter');
  assert.equal(await select.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#view-2d, #view-3d, .study-policy, .page-footer').count(), 0);
  await page.locator('#preview').click();
  await page.locator('#confirm-cancel').click();
  assert.equal(await page.locator('#contribution-list li').count(), 0);
  assert.equal(await select.getAttribute('aria-pressed'), 'true');
  // A bounded hand: no catalog or out-of-hand selection path.
  assert.equal(await page.locator('#browse, #catalog, #catalog-grid').count(), 0);
  assert.equal(await page.locator('#player-status [data-player-id] img').count(), 3);
  assert.equal(await page.locator('#player-status [data-status="deciding"]').count(), 3);
  assert.equal(await page.locator('#player-status [data-status="chosen"]').count(), 0, 'Local selection is not a confirmed choice');
  await page.evaluate(() => document.dispatchEvent(new CustomEvent('forge-select', { detail: { cardId: 'bid-take-tricks' } })));
  assert.equal(await hand.locator('[data-card-id="bid-take-tricks"]').count(), 0);
  assert.equal(await select.getAttribute('aria-pressed'), 'true');
  const fixedIds = await hand.locator('forge-card').evaluateAll((els) => els.map((el) => el.dataset.cardId));
  assert.equal(await page.locator('.fc-swap, #inspect-swap').count(), 0);
  await page.evaluate(() => document.dispatchEvent(new CustomEvent('forge-swap', { detail: { cardId: 'knockback' } })));
  assert.deepEqual(await hand.locator('forge-card').evaluateAll((els) => els.map((el) => el.dataset.cardId)), fixedIds);
  assert.deepEqual(await hand.locator('forge-card:not(.fc-blank)').evaluateAll((els) => els.map((el) => el.card.slot).sort((a, b) => a.localeCompare(b))), ['cooking','cooking','fps','fps','zombies','zombies']);
  await page.getByRole('button', { name: 'Show me Quick orders', exact: true }).click();
  await page.locator('#demo-slot').getByRole('button', { name: /Next step/i }).click();
  await page.locator('#inspect-select').click();
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Select Quick orders');
  await page.locator('#preview').click(); await page.locator('#confirm-add').click();
  await page.waitForFunction(() => document.activeElement?.id === 'wait-title');
  assert.equal(await page.locator('#contribution-list li').count(), 1);
  assert.equal(await hand.locator('button.fc-face:disabled').count(), 6);
  assert.equal(await hand.locator('.fc-swap').count(), 0);
  assert.equal(await blank.evaluate((el) => getComputedStyle(el).backgroundColor), blankBackground, 'Blank keeps its readable dark style while waiting');
  assert.equal(await page.locator('#player-status [data-player-id="you"]').getAttribute('data-status'), 'chosen');
  assert.equal(await page.locator('#player-status [data-player-id="mira"]').getAttribute('data-status'), 'deciding');
  assert.match(await page.locator('#player-status').getByText('1 / 3 chosen', { exact: true }).innerText(), /1 \/ 3 chosen/);
  assert.match(await page.locator('#player-status').getByText(/^Waiting for Mira and Lance/).innerText(), /Waiting for Mira and Lance/);
  assert.equal(await page.locator('#contribution-list li').count(), 1);
  await page.getByRole('button', { name: 'Details for Hot on your heels', exact: true }).click();
  assert.equal(await page.locator('#inspect-select').isDisabled(), true);
  assert.equal(await page.locator('#inspect-swap').count(), 0);
  await page.keyboard.press('Escape');
  // Even a stale event cannot turn waiting into an extra contribution or swap.
  const frozenHand = await hand.locator('forge-card').evaluateAll((els) => els.map((el) => el.dataset.cardId));
  await page.evaluate(() => {
    document.dispatchEvent(new CustomEvent('forge-select', { detail: { cardId: 'knockback' } }));
    document.dispatchEvent(new CustomEvent('forge-swap', { detail: { cardId: 'pursuers' } }));
    document.getElementById('confirm-add').click();
  });
  assert.deepEqual(await hand.locator('forge-card').evaluateAll((els) => els.map((el) => el.dataset.cardId)), frozenHand);
  assert.equal(await page.locator('#contribution-list li').count(), 1);
  assert.ok(await page.locator('#player-status [data-player-id] img').evaluateAll((imgs) => imgs.every((img) => img.complete && img.naturalWidth > 0)), 'Cat SVGs load');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: new URL('./verification/cat-wait-desktop.png', import.meta.url).pathname, fullPage: true });
  await page.locator('#reset').click();
  assert.equal(await page.locator('#contribution-list li').count(), 0);
  assert.equal(await hand.locator('[selected]').count(), 0);
  assert.equal(await hand.locator('[data-card-id="quick-orders"]').count(), 1);
  assert.equal(await page.locator('#player-status [data-status="deciding"]').count(), 3);
  assert.equal(await hand.locator('button.fc-face:enabled').count(), 6);
  await page.setViewportSize({ width: 930, height: 900 });
  const worldBounds = await page.locator('#world').boundingBox();
  const handBounds = await page.locator('.hand-section').boundingBox();
  assert.ok(worldBounds.y + worldBounds.height <= handBounds.y, 'World stays above the hand');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile must not overflow');
  await page.getByRole('button', { name: 'Show me Quick orders', exact: true }).click();
  assert.equal(await page.locator('#inspect-dialog').isVisible(), true);
  assert.equal(await page.evaluate(() => document.querySelector('#inspect-dialog').scrollWidth <= document.querySelector('#inspect-dialog').clientWidth), true);
  await page.screenshot({ path: new URL('./verification/card-inspect-mobile.png', import.meta.url).pathname });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Select Quick orders', exact: true }).click();
  await page.locator('#preview').click(); await page.locator('#confirm-add').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.locator('#player-status').screenshot({ path: new URL('./verification/cat-wait-mobile.png', import.meta.url).pathname });
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('#browse, #catalog').count(), 0);
  assert.equal(await page.locator('#player-status [data-player-id] img').count(), 3);
  assert.equal(await page.locator('#hand forge-card').count(), 7);
  assert.deepEqual(errors, [], 'Browser console/page errors');
  console.log('PASS: bounded hand; cat deciding/chosen states; one-contribution wait lock; inspect/select/review/confirm; fixed six options and no swaps; keyboard/focus; on-demand mini demos; clean interface; desktop/mobile; reset; no console errors.');
} finally { await browser.close(); }
